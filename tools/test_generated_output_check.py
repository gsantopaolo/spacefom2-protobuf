"""Tests for generated_output_check.py (run: python -m pytest tools)."""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))

from generated_output_check import (  # noqa: E402
    BASE_BEHIND,
    HAND_EDITED,
    REGENERATE_AFTER_MERGE,
    UP_TO_DATE,
    decide,
    main,
    matches,
)

# The proto workflow's configuration.
PROTO_OUT = ["proto/", "generator/field-ids.lock.json"]
PROTO_IN = ["fom/", "generator/", "buf.yaml"]
# The samples workflow's configuration.
SAMPLES_OUT = ["samples/generated/", "samples/data/"]
SAMPLES_IN = ["proto/", "samples/buf.gen.yaml", "samples/attribution.py", "samples/python/writer.py"]


def proto(changed, stale):
    return decide("proto", changed, stale, PROTO_OUT, PROTO_IN).outcome


def samples(changed, stale):
    return decide("samples", changed, stale, SAMPLES_OUT, SAMPLES_IN).outcome


def test_matches_directories_and_exact_paths():
    assert matches("proto/siso/a.proto", ["proto/"])
    assert not matches("protocol.md", ["proto/"])
    assert matches("buf.yaml", ["buf.yaml"])
    assert not matches("buf.yaml.bak", ["buf.yaml"])


@pytest.mark.parametrize("changed", [[], ["README.md"], ["fom/SOURCE.json"], ["proto/siso/spacefom/v1/entity.proto"]])
def test_up_to_date_passes_whatever_changed(changed):
    assert proto(changed, []) == UP_TO_DATE


def test_input_change_with_stale_output_waits_for_the_bot():
    assert proto(["fom/SOURCE.json"], ["proto/siso/spacefom/v1/entity.proto"]) == REGENERATE_AFTER_MERGE
    assert proto(["generator/spacefom_proto/__init__.py"],
                 ["proto/siso/spacefom/v1/datatypes.proto"]) == REGENERATE_AFTER_MERGE


def test_hand_edited_proto_fails():
    assert proto(["proto/siso/spacefom/v1/entity.proto"],
                 ["proto/siso/spacefom/v1/entity.proto"]) == HAND_EDITED


def test_lock_file_is_output_even_under_generator_dir():
    assert proto(["generator/field-ids.lock.json"], ["generator/field-ids.lock.json"]) == HAND_EDITED


def test_partial_regeneration_fails():
    # Inputs changed and some output committed, but the output is still stale.
    changed = ["fom/SOURCE.json", "proto/siso/spacefom/v1/entity.proto"]
    assert proto(changed, ["proto/siso/spacefom/v1/management.proto"]) == HAND_EDITED


def test_complete_regeneration_passes():
    changed = ["fom/SOURCE.json", "proto/siso/spacefom/v1/entity.proto", "generator/field-ids.lock.json"]
    assert proto(changed, []) == UP_TO_DATE


def test_unrelated_pr_while_base_is_behind_passes():
    assert proto(["README.md"], ["proto/siso/spacefom/v1/entity.proto"]) == BASE_BEHIND
    assert proto([".github/workflows/generate-proto.yml"], ["proto/x.proto"]) == BASE_BEHIND


def test_samples_proto_change_waits_for_the_bot():
    assert samples(["proto/siso/spacefom/v1/entity.proto"],
                   ["samples/generated/go/siso/spacefom/v1/entity.pb.go"]) == REGENERATE_AFTER_MERGE
    assert samples(["samples/python/writer.py"], ["samples/data/dynamical_entity.binpb"]) == REGENERATE_AFTER_MERGE


def test_samples_hand_edits_fail():
    assert samples(["samples/data/dynamical_entity.json"], ["samples/data/dynamical_entity.json"]) == HAND_EDITED
    assert samples(["samples/generated/csharp/Entity.cs"], ["samples/generated/csharp/Entity.cs"]) == HAND_EDITED


def test_summary_text():
    d = decide("proto", ["fom/SOURCE.json"], ["proto/a.proto"], PROTO_OUT, PROTO_IN)
    assert d.ok
    assert "will be regenerated by the bot after merge" in d.summary
    assert "`fom/SOURCE.json`" in d.summary and "`proto/a.proto`" in d.summary
    assert not decide("proto", ["proto/a.proto"], ["proto/a.proto"], PROTO_OUT, PROTO_IN).ok


def test_cli_exit_codes(tmp_path, capsys):
    changed, stale = tmp_path / "changed.txt", tmp_path / "stale.txt"
    args = ["--name", "proto", "--output", "proto/", "--output", "generator/field-ids.lock.json",
            "--input", "fom/", "--input", "generator/", "--changed", str(changed), "--stale", str(stale)]
    changed.write_text("fom/SOURCE.json\n")
    stale.write_text("proto/a.proto\n")
    assert main(args) == 0
    changed.write_text("proto/a.proto\n\n")
    assert main(args) == 1
    stale.write_text("")
    assert main(args) == 0
    assert "matches the generator" in capsys.readouterr().out
