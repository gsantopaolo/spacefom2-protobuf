"""Render protobuf files. Output depends only on the inputs: no timestamps or paths."""

from __future__ import annotations

import re
import textwrap

from . import __version__
from .ids import reserved
from .mapping import ProtoEnum, ProtoField, ProtoFile, ProtoMessage

PACKAGE = "siso.spacefom.v1"
PACKAGE_DIR = PACKAGE.replace(".", "/")
WIDTH = 80
INDENT = "  "
LIST_ITEM = re.compile(r"^\d+\.\s")
ATTRIBUTION = [
    "Derived from the SISO-STD-018-2020 (SpaceFOM) FOM modules.",
    "Reprinted with permission from SISO Inc.",
]


def _comment(paragraphs: list[str], indent: str = "") -> list[str]:
    lines: list[str] = []
    prefix = indent + "// "
    for i, para in enumerate(paragraphs):
        if i and not LIST_ITEM.match(para):
            lines.append(indent + "//")
        lines.extend(
            prefix + line
            for line in textwrap.wrap(
                para, WIDTH - len(prefix), break_long_words=False, break_on_hyphens=False
            )
        )
    return lines


def _header(f: ProtoFile, semantics: bool, interactions: bool) -> list[str]:
    m = f.module
    options = f"semantics={'on' if semantics else 'off'}, interactions={'on' if interactions else 'off'}"
    return [
        f"// Code generated by spacefom_proto {__version__}. DO NOT EDIT.",
        f"// Source: {m.filename}",
        f"// Source sha256: {m.sha256}",
        f"// FOM module: {m.model_name}, version {m.model_version}",
        f"// Options: {options}",
        "//",
        *("// " + line for line in ATTRIBUTION),
        "",
        'syntax = "proto3";',
        "",
        f"package {PACKAGE};",
    ]


def _field_line(f: ProtoField, number: int) -> str:
    label = f"{f.label} " if f.label else ""
    line = f"{INDENT}{label}{f.type} {f.name} = {number};"
    return f"{line}  // {f.trailing}" if f.trailing else line


def _message(msg: ProtoMessage, entry: dict, semantics: bool) -> list[str]:
    paragraphs = (msg.comment if semantics else []) + msg.note
    lines = _comment(paragraphs)
    lines.append(f"message {msg.name} {{")
    spaced = any(f.note or (semantics and f.comment) for f in msg.fields)
    for i, f in enumerate(msg.fields):
        if i and spaced:
            lines.append("")
        paragraphs = f.note + (f.comment if semantics else [])
        line = _field_line(f, entry["fields"][f.name])
        if len(line) > WIDTH:
            # Too long for a trailing comment: put the note above the field.
            paragraphs = paragraphs + [f.trailing]
            line = _field_line(ProtoField(f.name, f.type, f.label), entry["fields"][f.name])
        lines.extend(_comment(paragraphs, INDENT))
        lines.append(line)
    numbers, names = reserved(entry)
    if numbers or names:
        if msg.fields:
            lines.append("")
        if numbers:
            lines.append(f"{INDENT}reserved {', '.join(str(n) for n in numbers)};")
        if names:
            lines.append(f"{INDENT}reserved {', '.join(chr(34) + n + chr(34) for n in names)};")
    lines.append("}")
    return lines


def _enum(enum: ProtoEnum, semantics: bool) -> list[str]:
    lines = _comment((enum.comment if semantics else []) + enum.note)
    lines.append(f"enum {enum.name} {{")
    for v in enum.values:
        line = f"{INDENT}{v.name} = {v.number};"
        lines.append(f"{line}  // {v.trailing}" if v.trailing else line)
    lines.append("}")
    return lines


def render(f: ProtoFile, lock: dict, semantics: bool = True, interactions: bool = True) -> str:
    lines = _header(f, semantics, interactions)
    if f.imports:
        lines.append("")
        lines.extend(f'import "{PACKAGE_DIR}/{key}.proto";' for key in f.imports)
    for item in f.items:
        lines.append("")
        if isinstance(item, ProtoMessage):
            lines.extend(_message(item, lock["messages"][item.name], semantics))
        else:
            lines.extend(_enum(item, semantics))
    return "\n".join(line.rstrip() for line in lines) + "\n"
