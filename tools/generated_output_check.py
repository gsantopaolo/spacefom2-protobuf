"""Decide whether a pull request's stale generated output is acceptable (issue #19).

A workflow regenerates the output, then calls this with two lists:
  --changed  paths the pull request changes (git diff --name-only <base> HEAD)
  --stale    generated paths that differ after regenerating (git status --porcelain)

Outcomes:
  up-to-date               the committed output matches the generator: pass
  regenerate-after-merge   inputs changed, output left alone: pass; the bot
                           regenerates the output after the merge
  base-behind              the PR touches neither; the base branch is waiting
                           for a bot PR: pass
  hand-edited              the PR changes generated output that does not match
                           the generator (including a partial regeneration): fail

It prints a Markdown summary for $GITHUB_STEP_SUMMARY and exits 1 only for
hand-edited.

Usage:
  python tools/generated_output_check.py --name proto \
      --output proto/ --output generator/field-ids.lock.json \
      --input fom/ --input generator/ \
      --changed changed.txt --stale stale.txt
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

UP_TO_DATE = "up-to-date"
REGENERATE_AFTER_MERGE = "regenerate-after-merge"
BASE_BEHIND = "base-behind"
HAND_EDITED = "hand-edited"


@dataclass
class Decision:
    outcome: str
    summary: str

    @property
    def ok(self) -> bool:
        return self.outcome != HAND_EDITED


def matches(path: str, patterns: list[str]) -> bool:
    """A pattern ending in '/' matches everything under it; others match exactly."""
    return any(path.startswith(p) if p.endswith("/") else path == p for p in patterns)


def decide(name: str, changed: list[str], stale: list[str],
           outputs: list[str], inputs: list[str]) -> Decision:
    # Output paths are checked first: generator/field-ids.lock.json is output
    # even though it sits under the generator/ input directory.
    edited_output = sorted(p for p in changed if matches(p, outputs))
    changed_inputs = sorted(p for p in changed if not matches(p, outputs) and matches(p, inputs))
    stale = sorted(stale)

    if not stale:
        return Decision(UP_TO_DATE, f"The committed {name} output matches the generator.")
    listing = "\n".join(f"- `{p}`" for p in stale)
    if edited_output:
        edited = "\n".join(f"- `{p}`" for p in edited_output)
        return Decision(HAND_EDITED, (
            f"This pull request changes generated {name} output, but it does not match "
            f"what the generator produces. Either commit the complete regenerated output "
            f"or leave it untouched and let the bot regenerate it after the merge.\n\n"
            f"Changed output:\n{edited}\n\nDiffers from the generator:\n{listing}"
        ))
    if changed_inputs:
        inputs_listing = "\n".join(f"- `{p}`" for p in changed_inputs)
        return Decision(REGENERATE_AFTER_MERGE, (
            f"Generated {name} output will be regenerated by the bot after merge. "
            f"This pull request changes its inputs, and all checks ran on the freshly "
            f"generated output.\n\nChanged inputs:\n{inputs_listing}\n\n"
            f"Output that will change:\n{listing}"
        ))
    return Decision(BASE_BEHIND, (
        f"The generated {name} output on the base branch is behind its inputs, probably "
        f"while a bot pull request is waiting to be merged. This pull request does not "
        f"touch it, so the check passes.\n\nOutput that differs:\n{listing}"
    ))


def read_paths(path: Path) -> list[str]:
    return [line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--name", required=True, help="what is generated, for the summary")
    parser.add_argument("--output", action="append", required=True, help="generated path or dir/")
    parser.add_argument("--input", action="append", required=True, help="input path or dir/")
    parser.add_argument("--changed", type=Path, required=True)
    parser.add_argument("--stale", type=Path, required=True)
    args = parser.parse_args(argv)

    decision = decide(args.name, read_paths(args.changed), read_paths(args.stale),
                      args.output, args.input)
    print(decision.summary)
    return 0 if decision.ok else 1


if __name__ == "__main__":
    sys.exit(main())
