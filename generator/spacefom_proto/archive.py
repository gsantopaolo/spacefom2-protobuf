"""Copy the previous proto tree into history/ before it is replaced (plan §6)."""

from __future__ import annotations

import hashlib
import json
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

_HEADER = re.compile(
    r"^// Code generated by spacefom_proto (?P<version>\S+)\. DO NOT EDIT\.\n"
    r"// Source: (?P<file>\S+)\n"
    r"// Source sha256: (?P<sha256>[0-9a-f]{64})\n"
)


def read_headers(proto_dir: Path) -> list[dict]:
    headers = []
    for path in sorted(proto_dir.rglob("*.proto")):
        m = _HEADER.match(path.read_text(encoding="utf-8"))
        if m:
            headers.append({"proto": path.relative_to(proto_dir).as_posix(), **m.groupdict()})
    return headers


def archive(proto_dir: Path, history_dir: Path, main_commit: str, now: datetime | None = None) -> Path | None:
    """Archive proto_dir as history/<UTC-timestamp>_<fom-sha7>/. Returns None if there is nothing to archive."""
    headers = read_headers(proto_dir)
    if not headers:
        return None
    combined = hashlib.sha256(
        "".join(sorted(h["sha256"] for h in headers)).encode()
    ).hexdigest()
    stamp = (now or datetime.now(timezone.utc)).strftime("%Y%m%dT%H%M%SZ")
    target = history_dir / f"{stamp}_{combined[:7]}"
    if target.exists():
        raise FileExistsError(target)
    shutil.copytree(proto_dir, target / "proto")
    manifest = {
        "archived_at": stamp,
        "main_commit": main_commit,
        "generator_versions": sorted({h["version"] for h in headers}),
        "fom_sha256": {h["file"]: h["sha256"] for h in headers},
    }
    (target / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return target
